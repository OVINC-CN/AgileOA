// Lookup 只匹配代码登记的固定字段。
func Lookup(key string) (Definition, bool) {
	for _, field := range Fields {
		if field.Key == key {
			return field, true
		}
	}
	return Definition{}, false
}

// Label 将英文枚举显示为中文，自由文本保持原值。
func Label(field Definition, value string) string {
	if value == "" {
		return "未填写"
	}
	for _, option := range field.Options {
		if option.Value == value {
			return option.Label
		}
	}
	return value
}
